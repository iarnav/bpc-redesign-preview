/* BPC site features shared by every page:
   search (⌘K / Ctrl+K / "/"), scroll reveal, header-on-scroll, back-to-top,
   event countdown, share buttons, toast messages and the "Install app" button.
   The search index is generated by tools/build_search_index.py. */
(function () {
  const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  /* ---------- Toast ---------- */
  let toastTimer;
  function toast(message) {
    let el = document.querySelector('.toast');
    if (!el) {
      el = document.createElement('div');
      el.className = 'toast';
      el.setAttribute('role', 'status');
      el.setAttribute('aria-live', 'polite');
      document.body.appendChild(el);
    }
    el.textContent = message;
    el.classList.add('is-visible');
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => el.classList.remove('is-visible'), 2600);
  }

  /* ---------- Search ---------- */
  const QUICK_LINKS = [
    { title: 'Diwali at Corfe Castle', page: 'Events', url: 'events.html#diwali-corfe-castle', snippet: 'Sun 25 Oct 2026 · 4–9 PM with the National Trust' },
    { title: 'Upcoming events', page: 'Events', url: 'events.html', snippet: 'Festivals, celebrations and gatherings' },
    { title: 'Donate to BPC', page: 'Get Involved', url: 'donate.html#donate', snippet: 'Bank transfer, one-off or monthly' },
    { title: 'Our Team', page: 'About', url: 'about.html#team', snippet: 'The people behind BPC' },
    { title: 'Gallery', page: 'Gallery', url: 'gallery.html', snippet: 'Photos from our celebrations' }
  ];
  let searchIndex = null;
  let dialog, input, list, results = [], active = 0;

  const escapeHtml = s => s.replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  const normalise = s => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');

  function highlight(text, words) {
    let out = escapeHtml(text);
    words.forEach(w => {
      if (w.length < 2) return;
      const re = new RegExp('(' + w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + ')', 'ig');
      out = out.replace(re, '<mark>$1</mark>');
    });
    return out;
  }

  function score(entry, words) {
    const title = normalise(entry.title);
    const hay = normalise([entry.title, entry.snippet, entry.page, entry.keywords || ''].join(' '));
    let total = 0;
    for (const w of words) {
      if (!hay.includes(w)) return 0;           // every word must appear somewhere
      if (title.startsWith(w)) total += 6;
      else if (new RegExp('\\b' + w).test(title)) total += 4;
      else if (title.includes(w)) total += 3;
      else if (normalise(entry.keywords || '').includes(w)) total += 2;
      else total += 1;
    }
    // Events page is the canonical place for an event; headings beat sub-headings
    return total + (entry.page === 'Events' ? 1 : 0) + (entry.level <= 2 ? 0.5 : 0);
  }

  function render() {
    const q = normalise(input.value.trim());
    const words = q.split(/\s+/).filter(Boolean);
    if (!words.length) {
      results = QUICK_LINKS;
    } else {
      results = (searchIndex || [])
        .map(e => ({ e, s: score(e, words) }))
        .filter(r => r.s > 0)
        .sort((a, b) => b.s - a.s)
        .map(r => r.e)
        .filter((e, i, all) => all.findIndex(x => x.title.toLowerCase() === e.title.toLowerCase()) === i)  // one result per title
        .slice(0, 8);
    }
    active = 0;
    const heading = words.length ? '' : '<li class="search-group" role="presentation">Popular</li>';
    if (!results.length) {
      list.innerHTML = '<li class="search-empty" role="presentation">No results for “' + escapeHtml(input.value.trim()) + '”. Try “Diwali”, “donate” or “team”.</li>';
      input.setAttribute('aria-activedescendant', '');
      return;
    }
    list.innerHTML = heading + results.map((r, i) =>
      '<li role="option" id="search-opt-' + i + '" class="search-result' + (i === 0 ? ' is-active' : '') + '" aria-selected="' + (i === 0) + '">' +
        '<a href="' + r.url + '" tabindex="-1">' +
          '<span class="sr-page">' + escapeHtml(r.page) + '</span>' +
          '<span class="sr-title">' + highlight(r.title, words) + '</span>' +
          (r.snippet ? '<span class="sr-snippet">' + highlight(r.snippet, words) + '</span>' : '') +
        '</a></li>').join('');
    input.setAttribute('aria-activedescendant', 'search-opt-0');
  }

  function setActive(i) {
    const items = list.querySelectorAll('.search-result');
    if (!items.length) return;
    active = (i + items.length) % items.length;
    items.forEach((el, n) => {
      el.classList.toggle('is-active', n === active);
      el.setAttribute('aria-selected', String(n === active));
    });
    items[active].scrollIntoView({ block: 'nearest' });
    input.setAttribute('aria-activedescendant', 'search-opt-' + active);
  }

  function go(url) {
    const target = new URL(url, location.href);
    dialog.close();
    if (target.pathname === location.pathname && target.hash) {
      location.hash = target.hash;            // same page: just jump
    } else {
      location.href = target.href;
    }
  }

  function buildDialog() {
    dialog = document.createElement('dialog');
    dialog.className = 'search-dialog';
    dialog.setAttribute('aria-label', 'Search the site');
    dialog.innerHTML =
      '<div class="search-box">' +
        '<div class="search-field">' +
          '<svg width="20" height="20" viewBox="0 0 24 24" fill="none" aria-hidden="true"><circle cx="11" cy="11" r="7" stroke="currentColor" stroke-width="2"/><path d="m21 21-4.3-4.3" stroke="currentColor" stroke-width="2" stroke-linecap="round"/></svg>' +
          '<input type="search" placeholder="Search events, team, donations…" autocomplete="off" spellcheck="false" role="combobox" aria-expanded="true" aria-controls="search-results" aria-autocomplete="list">' +
          '<kbd class="search-esc">Esc</kbd>' +
        '</div>' +
        '<ul class="search-results" id="search-results" role="listbox"></ul>' +
        '<div class="search-foot"><span><kbd>↑</kbd><kbd>↓</kbd> to move</span><span><kbd>↵</kbd> to open</span><span><kbd>Esc</kbd> to close</span></div>' +
      '</div>';
    document.body.appendChild(dialog);
    input = dialog.querySelector('input');
    list = dialog.querySelector('.search-results');

    input.addEventListener('input', render);
    input.addEventListener('keydown', e => {
      if (e.key === 'ArrowDown') { e.preventDefault(); setActive(active + 1); }
      else if (e.key === 'ArrowUp') { e.preventDefault(); setActive(active - 1); }
      else if (e.key === 'Enter' && results[active]) { e.preventDefault(); go(results[active].url); }
    });
    list.addEventListener('click', e => {
      const a = e.target.closest('a');
      if (a) { e.preventDefault(); go(a.getAttribute('href')); }
    });
    list.addEventListener('mousemove', e => {
      const li = e.target.closest('.search-result');
      if (li) setActive([...list.querySelectorAll('.search-result')].indexOf(li));
    });
    // Click on the backdrop closes
    dialog.addEventListener('click', e => { if (e.target === dialog) dialog.close(); });
  }

  function openSearch() {
    if (!dialog) buildDialog();
    if (dialog.open) return;
    dialog.showModal();
    input.value = '';
    render();
    input.focus();
    if (!searchIndex) {
      fetch('assets/search-index.json')
        .then(r => r.json())
        .then(data => { searchIndex = data; if (input.value) render(); })
        .catch(() => { searchIndex = []; });
    }
  }

  document.querySelectorAll('.search-btn').forEach(btn => btn.addEventListener('click', openSearch));
  document.addEventListener('keydown', e => {
    const typing = /input|textarea|select/i.test(document.activeElement.tagName) || document.activeElement.isContentEditable;
    if ((e.key === 'k' || e.key === 'K') && (e.metaKey || e.ctrlKey)) { e.preventDefault(); openSearch(); }
    else if (e.key === '/' && !typing) { e.preventDefault(); openSearch(); }
  });
  // Show the right shortcut hint
  const isMac = /Mac|iPhone|iPad/.test(navigator.platform || navigator.userAgent);
  document.querySelectorAll('.search-kbd').forEach(k => { k.textContent = isMac ? '⌘K' : 'Ctrl K'; });

  /* ---------- Header shadow on scroll + back to top ---------- */
  const header = document.querySelector('.site-header');
  const toTop = document.createElement('button');
  toTop.className = 'to-top';
  toTop.type = 'button';
  toTop.setAttribute('aria-label', 'Back to top');
  toTop.innerHTML = '<svg width="20" height="20" viewBox="0 0 24 24" fill="none" aria-hidden="true"><path d="M12 19V5M5 12l7-7 7 7" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round"/></svg>';
  toTop.addEventListener('click', () => window.scrollTo({ top: 0, behavior: reduceMotion ? 'auto' : 'smooth' }));
  document.body.appendChild(toTop);
  let ticking = false;
  function onScroll() {
    const y = window.scrollY;
    if (header) header.classList.toggle('is-scrolled', y > 8);
    toTop.classList.toggle('is-visible', y > 700);
    ticking = false;
  }
  window.addEventListener('scroll', () => { if (!ticking) { ticking = true; requestAnimationFrame(onScroll); } }, { passive: true });
  onScroll();

  /* ---------- Scroll reveal ---------- */
  if (!reduceMotion && 'IntersectionObserver' in window) {
    const targets = document.querySelectorAll(
      'main .section-title, main .wwd-item, main .fe-card, main .event-card, main .event-row, main .value-card, ' +
      'main .highlight-card, main .tl-item, main .team-card, main .album-card, main .sponsor-tile, main .vm-card, ' +
      'main .bank-card, main .alloc-card, main .mission-grid > *, main .about-intro-grid > *, main .emblem-grid > *'
    );
    const io = new IntersectionObserver(entries => {
      entries.forEach(entry => {
        if (entry.isIntersecting) { entry.target.classList.add('is-visible'); io.unobserve(entry.target); }
      });
    }, { rootMargin: '0px 0px -8% 0px', threshold: 0.08 });
    targets.forEach(el => {
      // Stagger siblings slightly
      const siblings = [...el.parentElement.children].filter(c => c.matches && c.matches(el.tagName.toLowerCase() + '.' + [...el.classList][0]));
      el.style.setProperty('--reveal-delay', Math.min(siblings.indexOf(el), 5) * 70 + 'ms');
      el.classList.add('reveal');
      io.observe(el);
    });
    document.documentElement.classList.add('js-reveal');
  }

  /* ---------- Countdown ---------- */
  document.querySelectorAll('[data-countdown]').forEach(el => {
    const target = new Date(el.dataset.countdown).getTime();
    const out = el.querySelector('.countdown-value');
    function tick() {
      const ms = target - Date.now();
      if (ms <= 0) { el.hidden = true; return false; }
      const d = Math.floor(ms / 864e5), h = Math.floor(ms / 36e5) % 24, m = Math.floor(ms / 6e4) % 60;
      out.innerHTML = (d ? '<b>' + d + '</b> day' + (d === 1 ? '' : 's') + ' ' : '') + '<b>' + h + '</b> hr <b>' + m + '</b> min';
      return true;
    }
    if (tick()) setInterval(tick, 30000);
    el.hidden = target <= Date.now();
  });

  /* ---------- Share ---------- */
  document.querySelectorAll('[data-share]').forEach(btn => {
    btn.addEventListener('click', async () => {
      const url = new URL(btn.dataset.shareUrl || location.href, location.href).href;
      const data = { title: btn.dataset.shareTitle || document.title, text: btn.dataset.shareText || '', url };
      if (navigator.share) {
        try { await navigator.share(data); } catch (e) { /* cancelled */ }
      } else {
        try { await navigator.clipboard.writeText(url); toast('Link copied — paste it anywhere to share.'); }
        catch (e) { toast('Copy this link: ' + url); }
      }
    });
  });

  /* ---------- Calendar downloads: friendly confirmation ---------- */
  document.querySelectorAll('a[download][href$=".ics"]').forEach(a => {
    a.addEventListener('click', () => toast('Calendar file downloaded — open it to add the event.'));
  });

  /* ---------- Install app (PWA) ---------- */
  let deferredPrompt = null;
  const installBtns = document.querySelectorAll('[data-install]');
  window.addEventListener('beforeinstallprompt', e => {
    e.preventDefault();
    deferredPrompt = e;
    installBtns.forEach(b => { b.hidden = false; });
  });
  installBtns.forEach(b => b.addEventListener('click', async () => {
    if (!deferredPrompt) return;
    deferredPrompt.prompt();
    await deferredPrompt.userChoice;
    deferredPrompt = null;
    installBtns.forEach(x => { x.hidden = true; });
  }));
  window.addEventListener('appinstalled', () => toast('BPC app installed — find it on your home screen.'));

  window.BPC = { toast, openSearch };
})();
